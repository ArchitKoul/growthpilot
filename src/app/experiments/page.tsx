"use client";

import Link from "next/link";
import { ExperimentCard } from "@/components/experiment-card";
import { useExperiments } from "@/components/use-experiments";
import { Badge, Empty, PageHeader } from "@/components/ui";

export default function ExperimentsPage() {
  const entries = useExperiments();
  return (
    <>
      <PageHeader
        title="Experiment recommendations"
        description="Structured experiment proposals generated from supported findings. Each states the evidence, hypothesis, metrics, design, and what would support or reject it."
      />
      {entries.length === 0 ? (
        <Empty title="No experiments yet">
          Experiments are generated by investigations from supported findings.{" "}
          <Link href="/investigate" className="text-accent">Run an investigation →</Link>
        </Empty>
      ) : (
        <div className="space-y-8">
          {entries.map(({ exp, investigation }) => (
            <div key={`${investigation.id}-${exp.id}`} className="space-y-2">
              <div className="flex flex-wrap items-center justify-between gap-2 text-xs text-muted">
                <span>
                  From:{" "}
                  <Link href={`/investigate?id=${investigation.id}`} className="text-accent">
                    “{investigation.question.slice(0, 90)}
                    {investigation.question.length > 90 ? "…" : ""}”
                  </Link>{" "}
                  · {investigation.dataset.name} <Badge tone={investigation.mode === "live" ? "good" : "warn"}>{investigation.mode}</Badge>
                </span>
                <Link
                  href={`/briefs?exp=${encodeURIComponent(exp.id)}&inv=${investigation.id}`}
                  className="rounded-lg border border-line bg-surface px-2.5 py-1 text-xs font-medium text-ink hover:bg-surface-2"
                >
                  Create product brief →
                </Link>
              </div>
              <ExperimentCard exp={exp} />
            </div>
          ))}
        </div>
      )}
    </>
  );
}
